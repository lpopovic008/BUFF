/** The same, by key (see collegeKey). */
const BY_KEY = new Map(Object.entries(ABBREVIATIONS).map(([name, short]) => [collegeKey(name), short]));

/** Words a made-up short name leaves out. */
const FILLER = new Set(["of", "the", "at", "and", "&"]);

/**
 * A player's college's short name: the school's own (see ABBREVIATIONS), by any of its names — or, for a school not
 * on file, its name if that's short, its words' initials if it's several ("Grand Valley State": GVS), or its first four
 * letters. Null when he has none.
 */
export function collegeAbbreviation(college: string | null | undefined): string | null {
  if (!college?.trim()) return null;
  const key = collegeKey(college);
  const known = BY_KEY.get(ALIASES[key] ?? key) ?? BY_KEY.get(key);
  if (known) return known;
  const words = college
    .replace(/[()]/g, " ")
    .split(/[\s.-]+/)
    .filter((w) => w && !FILLER.has(w.toLowerCase()));
  if (college.replace(/[^A-Za-z]/g, "").length <= 4) return college.replace(/[^A-Za-z&]/g, "").toUpperCase();
  if (words.length > 1) return words.map((w) => w[0].toUpperCase()).join("").slice(0, 5);
  return words[0].slice(0, 4).toUpperCase();
}
