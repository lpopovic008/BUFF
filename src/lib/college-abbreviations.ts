// Colleges' short names for the players' cards — the schools NFL players come from, as their scoreboards and broadcasts
// abbreviate them (ALA, OSU, UGA), kept here so a card needs no lookup; any other school's made up from its name. In
// place of their logos, which are the schools' trademarks.

/** A name as it's compared: lowercase letters and digits only, "St." as "state", no "University (of)". */
export function collegeKey(name: string): string {
  return name
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/\buniversity\b|\buniv\.?\b|\bof\b|\bthe\b/g, "")
    .replace(/\bst\.?(?=\s|$)/g, "state")
    .replace(/[^a-z0-9]/g, "");
}

